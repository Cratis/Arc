using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Cratis.Arc.Generators;

/// <summary>
/// Generates typed Execute and Compensate calls for accessible operation declarations, without service captures.
/// </summary>
[Generator]
public class CommandOperationGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var operations = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is TypeDeclarationSyntax { BaseList: not null },
            static (syntax, _) => syntax.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)syntax.Node) as INamedTypeSymbol)
            .Where(static type => type?.IsAbstract == false && type.TypeKind != TypeKind.Interface &&
                CommandOperationConvention.IsOperation(type) && CommandOperationConvention.IsAccessible(type))
            .Collect();
        context.RegisterSourceOutput(operations, static (output, types) =>
        {
            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Cratis.Arc.Commands.Generated;\ninternal static class OperationRegistration\n{\n    [global::System.Runtime.CompilerServices.ModuleInitializer]\n    internal static void Initialize()\n    {\n");
            foreach (var type in types.Distinct<INamedTypeSymbol?>(SymbolEqualityComparer.Default))
            {
                var execute = CommandOperationConvention.Methods(type!, "Execute");
                var compensate = CommandOperationConvention.Methods(type!, "Compensate");
                if (execute.Length != 1 || !CommandOperationConvention.IsValid(execute[0], false) ||
                    compensate.Length > 1 || compensate.Any(method => !CommandOperationConvention.IsValid(method, true)))
                {
                    continue;
                }

                var name = type!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                source.Append("        global::Cratis.Arc.Commands.CommandOperationInvokers.Register(typeof(").Append(name).AppendLine("), new(");
                AppendMethod(source, name, execute[0]);
                source.AppendLine(",");
                if (compensate.Length == 1)
                {
                    AppendMethod(source, name, compensate[0]);
                }
                else
                {
                    source.Append("            [], null");
                }

                source.AppendLine("));");
            }

            source.AppendLine("    }\n}");
            output.AddSource("CommandOperations.g.cs", source.ToString());
        });
    }

    static void AppendMethod(StringBuilder source, string type, IMethodSymbol method)
    {
        var parameters = method.Parameters.Select(parameter => parameter.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).ToArray();
        source.Append("            [").Append(string.Join(", ", parameters.Select(parameter => $"typeof({parameter})"))).AppendLine("],");
        var call = $"(({type})operation).{method.Name}({string.Join(", ", parameters.Select((parameter, index) => $"({parameter})arguments[{index}]!"))})";
        source.Append("            static (operation, arguments) => ");
        if (method.ReturnsVoid)
        {
            source.Append("{ ").Append(call).Append("; return global::System.Threading.Tasks.ValueTask.CompletedTask; }");
        }
        else if (method.ReturnType.ToDisplayString() == "System.Threading.Tasks.Task")
        {
            source.Append("new global::System.Threading.Tasks.ValueTask(").Append(call).Append(')');
        }
        else
        {
            source.Append(call);
        }
    }
}
