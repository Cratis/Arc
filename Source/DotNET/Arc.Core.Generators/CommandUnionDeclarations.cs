using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Cratis.Arc.Generators;

/// <summary>
/// Finds nameable closed native union declarations throughout command return graphs, including collections.
/// Unlike result factories, declarations include operation and validation cases.
/// </summary>
internal static class CommandUnionDeclarations
{
    /// <summary>
    /// Registers incremental command return-graph discovery and declaration emission.
    /// </summary>
    /// <param name="context">The generator initialization context.</param>
    internal static void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Cratis.Arc.Commands.ModelBound.CommandAttribute",
            static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.TypeDeclarationSyntax,
            static (syntax, _) => new EquatableArray<string>(Registrations((INamedTypeSymbol)syntax.TargetSymbol, syntax.SemanticModel.Compilation)))
            .Collect();
        context.RegisterSourceOutput(declarations, static (output, commands) =>
        {
            var registrations = commands.SelectMany(command => command).Distinct().OrderBy(value => value, StringComparer.Ordinal).ToArray();
            if (registrations.Length == 0) return;
            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Cratis.Arc.Commands.Generated;\ninternal static class CommandUnionRegistration\n{\n    [global::System.Runtime.CompilerServices.ModuleInitializer]\n    internal static void Initialize()\n    {\n");
            foreach (var registration in registrations) source.AppendLine(registration);
            source.AppendLine("    }\n}");
            output.AddSource("CommandUnions.g.cs", source.ToString());
        });
    }

    static IEnumerable<string> Registrations(INamedTypeSymbol command, Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName("Cratis.Arc.Commands.CommandUnionMetadata") is null) yield break;
        var visited = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var method in CommandOperationConvention.Methods(command, "Handle").Where(method => !method.IsStatic && !method.ReturnsVoid))
        {
            foreach (var union in Visit(method.ReturnType, compilation, visited))
            {
                var name = union.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var cases = string.Join(", ", CaseTypes(union).Select(type => $"typeof({type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})"));
                yield return $"        global::Cratis.Arc.Commands.CommandUnionMetadata.Register(typeof({name}), new global::System.Type[] {{ {cases} }}, static value => ((global::System.Runtime.CompilerServices.IUnion)({name})value).Value);";
            }
        }
    }

    static IEnumerable<INamedTypeSymbol> Visit(ITypeSymbol type, Compilation compilation, HashSet<ITypeSymbol> visited)
    {
        if (!visited.Add(type)) return [];
        return type switch
        {
            IArrayTypeSymbol array => Visit(array.ElementType, compilation, visited),
            INamedTypeSymbol named => VisitNamed(named, compilation, visited),
            _ => []
        };
    }

    static IEnumerable<INamedTypeSymbol> VisitNamed(INamedTypeSymbol type, Compilation compilation, HashSet<ITypeSymbol> visited)
    {
        var descendants = Children(type, compilation).SelectMany(child => Visit(child, compilation, visited));
        return CanRegister(type, compilation) ? new[] { type }.Concat(descendants) : descendants;
    }

    static bool CanRegister(INamedTypeSymbol type, Compilation compilation) => IsNativeUnion(type, compilation) &&
        TypeNaming.CanBeNamed(type, compilation) && CaseTypes(type).All(caseType => TypeNaming.CanBeNamed(caseType, compilation));

    static bool IsNativeUnion(INamedTypeSymbol type, Compilation compilation) =>
        compilation.GetTypeByMetadataName("System.Runtime.CompilerServices.IUnion") is { } contract &&
        SymbolEqualityComparer.Default.Equals(contract.ContainingAssembly, compilation.GetSpecialType(SpecialType.System_Object).ContainingAssembly) &&
        type.AllInterfaces.Any(implemented => SymbolEqualityComparer.Default.Equals(implemented, contract));

    static IEnumerable<ITypeSymbol> CaseTypes(INamedTypeSymbol type) => type.InstanceConstructors
        .Where(constructor => constructor.DeclaredAccessibility == Accessibility.Public &&
            UnionCaseConvention.IsCaseConstructor(
                constructor.IsImplicitlyDeclared || constructor.GetAttributes().Any(attribute =>
                    attribute.AttributeClass?.ToDisplayString() == UnionCaseConvention.CompilerGeneratedAttributeName),
                constructor.Parameters.Length))
        .Select(constructor => constructor.Parameters[0].Type);

    static IEnumerable<ITypeSymbol> Children(INamedTypeSymbol type, Compilation compilation)
    {
        if (IsNativeUnion(type, compilation)) return CaseTypes(type);
        if (type.IsTupleType) return type.TupleElements.Select(element => element.Type);
        if (IsWrapper(type)) return type.TypeArguments;
        if (OneOfArguments(type) is { IsDefault: false } arguments) return arguments;
        return type.AllInterfaces.Where(IsEnumerable).Select(contract => contract.TypeArguments[0]);
    }

    static bool IsWrapper(INamedTypeSymbol type) => IsEnumerable(type) ||
        (type.ContainingNamespace.ToDisplayString() == "System" && (type.Name == "Tuple" || type.Name == "ValueTuple")) ||
        (type.ContainingNamespace.ToDisplayString() == "System.Threading.Tasks" && (type.Name == "Task" || type.Name == "ValueTask")) ||
        type.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;

    static bool IsEnumerable(INamedTypeSymbol type) => type.OriginalDefinition.SpecialType == SpecialType.System_Collections_Generic_IEnumerable_T;

    static ImmutableArray<ITypeSymbol> OneOfArguments(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (current.ContainingNamespace.ToDisplayString() == "OneOf" && (current.Name == "OneOf" || current.Name == "OneOfBase")) return current.TypeArguments;
        }
        return default;
    }
}
