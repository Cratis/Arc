using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Cratis.Arc.Generators;

/// <summary>
/// Emits the command key properties and read model key types the read protection lookup would otherwise discover through
/// reflection, only when Chronicle's registry for them is referenced.
/// </summary>
internal static class CommandReadModelKeyGeneration
{
    const string Registry = "Cratis.Arc.Chronicle.ReadModels.CommandReadModelKeys";
    const string Property = "global::Cratis.Arc.Chronicle.ReadModels.CommandReadModelKeyProperty";
    const string ValidatorBase = "Cratis.Arc.Commands.CommandValidator<T>";
    static readonly SymbolDisplayFormat _format = SymbolDisplayFormat.FullyQualifiedFormat
        .RemoveMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    /// <summary>
    /// Gets the type a command validator validates.
    /// </summary>
    /// <param name="validator">The validator type.</param>
    /// <returns>The validated type, or <see langword="null"/> when the type is not a command validator.</returns>
    internal static INamedTypeSymbol? ValidatedType(INamedTypeSymbol validator)
    {
        for (var current = validator.BaseType; current is not null; current = current.BaseType)
        {
            if (current.OriginalDefinition.ToDisplayString() == ValidatorBase)
            {
                return current.TypeArguments[0] as INamedTypeSymbol;
            }
        }

        return null;
    }

    /// <summary>
    /// Emits the registrations for a consuming compilation.
    /// </summary>
    /// <param name="output">The generation output.</param>
    /// <param name="commands">The command metadata names.</param>
    /// <param name="validators">The command validator metadata names.</param>
    /// <param name="readModels">The read model metadata names.</param>
    /// <param name="compilation">The consuming compilation.</param>
    internal static void Emit(SourceProductionContext output, ImmutableArray<string> commands, ImmutableArray<string> validators, ImmutableArray<string> readModels, Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName(Registry) is null ||
            compilation.Assembly.GetAttributes().Concat(compilation.SourceModule.GetAttributes())
                .Any(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Diagnostics.CodeAnalysis.ExperimentalAttribute"))
        {
            return;
        }

        var validatorTypes = ModelGraphWalkerGenerator.TypesNamed(validators, compilation).ToArray();
        var commandTypes = ModelGraphWalkerGenerator.TypesNamed(commands, compilation)
            .Concat(validatorTypes.Select(ValidatedType).OfType<INamedTypeSymbol>())
            .Where(type => type.TypeKind is TypeKind.Class or TypeKind.Struct && !type.IsAbstract)
            .Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
            .OrderBy(type => type.ToDisplayString(_format), StringComparer.Ordinal)
            .ToArray();
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Cratis.Arc.Chronicle.ReadModels.Generated;\ninternal static class CommandReadModelKeyRegistration\n{\n    [global::System.Runtime.CompilerServices.ModuleInitializer]\n    internal static void Initialize()\n    {\n");
        var emitted = false;
        foreach (var command in commandTypes)
        {
            if (RenderCommand(source, command, compilation, output.CancellationToken))
            {
                emitted = true;
            }
            else
            {
                output.ReportDiagnostic(Diagnostic.Create(ArcGeneratorDiagnostics.CommandKeysNotGenerated, command.Locations.FirstOrDefault(location => location.IsInSource) ?? Location.None, command.ToDisplayString()));
            }
        }

        var models = commandTypes.SelectMany(ModelParameters)
            .Concat(validatorTypes.SelectMany(validator => validator.InstanceConstructors.SelectMany(constructor => constructor.Parameters)).Select(parameter => parameter.Type))
            .Concat(ModelGraphWalkerGenerator.TypesNamed(readModels, compilation));
        foreach (var model in models.OfType<INamedTypeSymbol>()
            .Where(type => type.TypeKind == TypeKind.Class && type.SpecialType == SpecialType.None && TypeNaming.CanBeNamed(type, compilation))
            .Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
            .OrderBy(type => type.ToDisplayString(_format), StringComparer.Ordinal))
        {
            emitted |= RenderModel(source, model, compilation);
        }

        if (emitted)
        {
            source.AppendLine("    }\n}");
            output.AddSource("CommandReadModelKeys.g.cs", source.ToString());
        }
    }

    static IEnumerable<ITypeSymbol> ModelParameters(INamedTypeSymbol command) =>
        ProtectedReadModelKeyGeneration.Members(command).OfType<IMethodSymbol>()
            .Where(method => method.Name is "Handle" or "Provide")
            .SelectMany(method => method.Parameters.Select(parameter => parameter.Type));

    static bool RenderCommand(StringBuilder source, INamedTypeSymbol command, Compilation compilation, CancellationToken cancellationToken)
    {
        var properties = ModelGraphWalkerTypes.WalkedProperties(command, compilation, cancellationToken, publicGettersOnly: true);
        if (properties is null || !properties.TrueForAll(property => TypeNaming.CanBeNamed(property.Type, compilation)))
        {
            return false;
        }

        var name = command.ToDisplayString(_format);
        source.Append("        global::").Append(Registry).Append(".RegisterCommand(typeof(").Append(name).Append(')');
        foreach (var property in properties)
        {
            var declaring = property.ContainingType.ToDisplayString(_format);
            var cast = string.Equals(declaring, name, StringComparison.Ordinal) ? $"({name})instance" : $"({declaring})({name})instance";
            source.AppendLine(",").Append("            new ").Append(Property).Append('(')
                .Append(SymbolDisplay.FormatLiteral(property.Name, true)).Append(", typeof(").Append(property.Type.ToDisplayString(_format))
                .Append("), static instance => (").Append(cast).Append(").@").Append(property.Name).Append(')');
        }

        source.AppendLine(");");
        return true;
    }

    static bool RenderModel(StringBuilder source, INamedTypeSymbol model, Compilation compilation)
    {
        var id = ProtectedReadModelKeyGeneration.IdProperty(model);
        if (id is not null && !TypeNaming.CanBeNamed(id.Type, compilation))
        {
            return false;
        }

        source.Append("        global::").Append(Registry).Append(".DeclareModelKey(typeof(").Append(model.ToDisplayString(_format)).Append("), ")
            .Append(id is null ? "null" : $"typeof({id.Type.ToDisplayString(_format)})").AppendLine(");");
        return true;
    }
}
