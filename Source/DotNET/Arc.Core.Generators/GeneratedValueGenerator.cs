using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Cratis.Arc.Generators;

/// <summary>
/// Generates module-initializer registrations for the generatable types declared by command Handle parameters.
/// </summary>
[Generator]
public class GeneratedValueGenerator : IIncrementalGenerator
{
    const string AttributeName = "Cratis.Arc.Commands.ModelBound.GeneratedValueAttribute";
    const string CommandAttributeName = "Cratis.Arc.Commands.ModelBound.CommandAttribute";
    const string GeneratableName = "Cratis.Concepts.IGeneratable<TSelf>";
    const string ContextGeneratableName = "Cratis.Concepts.IGeneratableInContext<TSelf>";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName,
            static (node, _) => node is ParameterSyntax,
            static (syntax, _) => TypeFor(syntax))
            .Where(static type => type is not null)
            .Collect();
        context.RegisterSourceOutput(types, static (output, candidates) =>
        {
            var names = candidates.OfType<(string Name, bool Context)>().Distinct().OrderBy(type => type.Name, StringComparer.Ordinal).ToArray();
            if (names.Length == 0)
            {
                return;
            }

            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Cratis.Arc.Commands.Generated;\ninternal static class GeneratedValueRegistration\n{\n    [global::System.Runtime.CompilerServices.ModuleInitializer]\n    internal static void Initialize()\n    {\n");
            foreach (var type in names)
            {
                source.Append("        global::Cratis.Arc.Commands.GeneratedValueFactories.Register(typeof(").Append(type.Name)
                    .Append(type.Context ? "), static context => global::Cratis.Arc.Commands.GeneratedValueFactories.New<" : "), static () => global::Cratis.Arc.Commands.GeneratedValueFactories.New<")
                    .Append(type.Name).AppendLine(type.Context ? ">(context));" : ">());");
            }

            source.AppendLine("    }\n}");
            output.AddSource("GeneratedValues.g.cs", source.ToString());
        });
    }

    static (string Name, bool Context)? TypeFor(GeneratorAttributeSyntaxContext syntax)
    {
        if (syntax.TargetSymbol is not IParameterSymbol { RefKind: RefKind.None, ContainingSymbol: IMethodSymbol method } parameter ||
            !IsValidDeclaration(method, parameter) || !IsGeneratable(parameter.Type))
        {
            return null;
        }

        return (parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), Implements(parameter.Type, ContextGeneratableName));
    }

    static bool IsValidDeclaration(IMethodSymbol method, IParameterSymbol parameter) => method.Name == "Handle" && !method.IsStatic &&
        method.ContainingType.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == CommandAttributeName) &&
        parameter.NullableAnnotation != NullableAnnotation.Annotated && CanReference(parameter.Type);

    static bool IsGeneratable(ITypeSymbol type) => Implements(type, GeneratableName) || Implements(type, ContextGeneratableName);

    static bool Implements(ITypeSymbol type, string name) => type.AllInterfaces.Any(contract =>
        contract.OriginalDefinition.ToDisplayString() == name && SymbolEqualityComparer.Default.Equals(contract.TypeArguments[0], type));

    static bool CanReference(ITypeSymbol type) => type is INamedTypeSymbol named &&
        !named.IsFileLocal && named.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal &&
        !named.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "System.ObsoleteAttribute" ||
            attribute.AttributeClass?.ToDisplayString() == "System.Diagnostics.CodeAnalysis.ExperimentalAttribute") &&
        named.TypeArguments.All(CanReference) &&
        (named.ContainingType is null || CanReference(named.ContainingType));
}
