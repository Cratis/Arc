using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Cratis.Arc.Generators;

/// <summary>
/// Emits distinct complete composite descriptors only when Chronicle's optional registry is referenced.
/// </summary>
internal static class ProtectedReadModelKeyGeneration
{
    const string Registry = "Cratis.Arc.Chronicle.ReadModels.ProtectedReadModelKeyAccessors";
    const string Member = "global::Cratis.Arc.Chronicle.ReadModels.ProtectedReadModelKeyMember";
    static readonly SymbolDisplayFormat _format = SymbolDisplayFormat.FullyQualifiedFormat;
    static readonly HashSet<string> _scalarTypeNames = new(StringComparer.Ordinal) { "Guid", "DateTimeOffset", "DateOnly", "TimeOnly", "TimeSpan" };

    /// <summary>
    /// Emits composite descriptors and declared-key coverage metadata for a consuming compilation.
    /// </summary>
    /// <param name="output">The generation output.</param>
    /// <param name="commands">The command metadata names.</param>
    /// <param name="readModels">The read model metadata names.</param>
    /// <param name="compilation">The consuming compilation.</param>
    internal static void Emit(SourceProductionContext output, ImmutableArray<string> commands, ImmutableArray<string> readModels, Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName(Registry) is null ||
            compilation.Assembly.GetAttributes().Concat(compilation.SourceModule.GetAttributes())
                .Any(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Diagnostics.CodeAnalysis.ExperimentalAttribute"))
        {
            return;
        }

        var commandTypes = ModelGraphWalkerGenerator.TypesNamed(commands, compilation).ToArray();
        var keys = commandTypes.Select(command => (Command: command, Keys: DeclaredKeys(command).Distinct<ITypeSymbol>(SymbolEqualityComparer.Default).ToArray())).ToArray();
        var roots = commandTypes.Cast<ITypeSymbol>()
            .Concat(ModelGraphWalkerGenerator.QueryArgumentTypes(ModelGraphWalkerGenerator.TypesNamed(readModels, compilation), compilation))
            .Concat(keys.SelectMany(entry => entry.Keys)).ToArray();
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Cratis.Arc.Chronicle.ReadModels.Generated;\ninternal static class ProtectedReadModelKeyRegistration\n{\n    [global::System.Runtime.CompilerServices.ModuleInitializer]\n    internal static void Initialize()\n    {\n");
        var covered = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var type in ModelGraphWalkerTypes.ReachableTypes(roots, compilation, output.CancellationToken)
            .Where(IsComposite).OrderBy(type => type.ToDisplayString(_format), StringComparer.Ordinal))
        {
            var properties = ModelGraphWalkerTypes.WalkedProperties(type, compilation, output.CancellationToken, publicGettersOnly: true);
            if (properties is null) continue;
            covered.Add(type);
            RenderDescriptor(source, type, properties);
        }

        foreach (var entry in keys.Where(entry => TypeNaming.CanBeNamed(entry.Command, compilation)))
        {
            var types = entry.Keys.Where(type => TypeNaming.CanBeNamed(type, compilation)).ToArray();
            if (types.Length == 0) continue;
            source.Append("        global::").Append(Registry).Append(".DeclareKeyTypes(typeof(")
                .Append(entry.Command.ToDisplayString(_format)).Append(')');
            foreach (var type in types)
            {
                source.Append(", typeof(").Append(type.ToDisplayString(_format)).Append(')');
            }
            source.AppendLine(");");
        }

        foreach (var type in keys.SelectMany(entry => entry.Keys).Select(UnwrapNullable).Distinct<ITypeSymbol>(SymbolEqualityComparer.Default)
            .OfType<INamedTypeSymbol>().Where(type => IsComposite(type) && !covered.Contains(type)))
        {
            output.ReportDiagnostic(Diagnostic.Create(ArcGeneratorDiagnostics.AccessorMissing, type.Locations.FirstOrDefault(location => location.IsInSource) ?? Location.None, type.ToDisplayString()));
        }

        source.AppendLine("    }\n}");
        if (covered.Count > 0 || keys.Any(entry => entry.Keys.Length > 0))
        {
            output.AddSource("ProtectedReadModelKeyAccessors.g.cs", source.ToString());
        }
    }

    static IEnumerable<ITypeSymbol> DeclaredKeys(INamedTypeSymbol command)
    {
        var properties = Members(command).OfType<IPropertySymbol>()
            .Where(property => !property.IsStatic && property.Parameters.Length == 0 && property.GetMethod?.DeclaredAccessibility == Accessibility.Public).ToArray();
        foreach (var property in properties.Where(property => HasKey(property) || IsEventSourceId(property.Type)))
        {
            yield return property.Type;
        }
        foreach (var parameter in Members(command).OfType<IMethodSymbol>().SelectMany(method => method.Parameters))
        {
            var lookup = parameter.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == "Cratis.Arc.Commands.LookUpByAttribute");
            if (lookup?.ConstructorArguments.FirstOrDefault().Value is string name)
            {
                foreach (var property in properties.Where(property => property.Name == name)) yield return property.Type;
            }
            else if (parameter.Type is INamedTypeSymbol model && model.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "Cratis.Arc.Queries.ModelBound.ReadModelAttribute"))
            {
                var id = Members(model).OfType<IPropertySymbol>().FirstOrDefault(property => property.Name == "Id");
                foreach (var property in properties.Where(property => SymbolEqualityComparer.Default.Equals(property.Type, id?.Type))) yield return property.Type;
            }
        }
    }

    static IEnumerable<ISymbol> Members(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            foreach (var member in current.GetMembers()) yield return member;
        }
    }

    static bool HasKey(IPropertySymbol property) =>
        property.GetAttributes().Any(IsKeyAttribute) || property.ContainingType.InstanceConstructors.SelectMany(constructor => constructor.Parameters)
            .Any(parameter => parameter.Name == property.Name && SymbolEqualityComparer.Default.Equals(parameter.Type, property.Type) && parameter.GetAttributes().Any(IsKeyAttribute));

    static bool IsKeyAttribute(AttributeData attribute) => attribute.AttributeClass?.ToDisplayString() == "Cratis.Chronicle.Keys.KeyAttribute";

    static bool IsEventSourceId(ITypeSymbol type)
    {
        for (var current = type as INamedTypeSymbol; current is not null; current = current.BaseType)
        {
            if (current.ContainingNamespace.ToDisplayString() == "Cratis.Chronicle.Events" && current.Name == "EventSourceId") return true;
        }

        return false;
    }

    static ITypeSymbol UnwrapNullable(ITypeSymbol type) =>
        type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable ? nullable.TypeArguments[0] : type;

    static bool IsScalar(INamedTypeSymbol type) =>
        type.TypeKind == TypeKind.Enum ||
        type.SpecialType is SpecialType.System_Boolean or SpecialType.System_Char or SpecialType.System_SByte or SpecialType.System_Byte or
            SpecialType.System_Int16 or SpecialType.System_UInt16 or SpecialType.System_Int32 or SpecialType.System_UInt32 or
            SpecialType.System_Int64 or SpecialType.System_UInt64 or SpecialType.System_Single or SpecialType.System_Double or
            SpecialType.System_IntPtr or SpecialType.System_UIntPtr or SpecialType.System_String or SpecialType.System_Decimal or SpecialType.System_DateTime ||
        (type.ContainingNamespace.ToDisplayString() == "System" && _scalarTypeNames.Contains(type.MetadataName));

    static bool IsComposite(INamedTypeSymbol type) =>
        type.SpecialType == SpecialType.None && type.TypeKind is TypeKind.Class or TypeKind.Struct &&
        !type.IsAbstract && !IsScalar(type) && !type.IsTupleType && !IsEventSourceId(type) &&
        !type.AllInterfaces.Any(@interface => @interface.ToDisplayString() == "System.Runtime.CompilerServices.ITuple") &&
        !HasConceptBase(type);

    static bool HasConceptBase(INamedTypeSymbol type)
    {
        for (var current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (current.ContainingNamespace.ToDisplayString() == "Cratis.Concepts" && current.Name == "ConceptAs") return true;
        }

        return false;
    }

    static void RenderDescriptor(StringBuilder source, INamedTypeSymbol type, IEnumerable<IPropertySymbol> properties)
    {
        var name = type.ToDisplayString(_format);
        source.Append("        global::").Append(Registry).Append(".Register<").Append(name).AppendLine(">(")
            .Append("            new ").Append(Member).Append('<').Append(name).AppendLine(">[]\n            {");
        foreach (var property in properties)
        {
            var declaring = property.ContainingType.ToDisplayString(_format);
            source.Append("                new(").Append(SymbolDisplay.FormatLiteral(property.Name, true))
                .Append(", static instance => ((").Append(declaring).Append(")instance).@").Append(property.Name).AppendLine("),");
        }
        source.AppendLine("            });");
    }
}
