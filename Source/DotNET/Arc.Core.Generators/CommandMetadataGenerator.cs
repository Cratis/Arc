using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Cratis.Arc.Generators;

/// <summary>
/// Preserves model-bound command methods for reflection-based discovery and execution under trimming and NativeAOT.
/// </summary>
[Generator]
public class CommandMetadataGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var commands = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Cratis.Arc.Commands.ModelBound.CommandAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (syntax, _) => (INamedTypeSymbol)syntax.TargetSymbol)
            .Collect();

        context.RegisterSourceOutput(commands, static (output, types) =>
        {
            if (types.Length == 0)
            {
                return;
            }

            var source = new StringBuilder("// <auto-generated/>\nnamespace Cratis.Arc.Commands.Generated;\ninternal static class CommandMetadata\n{\n");
            foreach (var type in types.Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default).OrderBy(MetadataName, StringComparer.Ordinal))
            {
                // Metadata names also support private, file-local and open generic command declarations.
                source.Append("    [global::System.Diagnostics.CodeAnalysis.DynamicDependency(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicMethods | global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.NonPublicMethods, ")
                    .Append(SymbolDisplay.FormatLiteral(MetadataName(type), true)).Append(", ")
                    .Append(SymbolDisplay.FormatLiteral(type.ContainingAssembly.Identity.Name, true)).AppendLine(")]");
            }

            source.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]\n    internal static void Initialize() { }\n}");
            output.AddSource("CommandMetadata.g.cs", source.ToString());
        });
    }

    static string MetadataName(INamedTypeSymbol type)
    {
        if (type.ContainingType is { } containingType)
        {
            return $"{MetadataName(containingType)}+{type.MetadataName}";
        }

        return type.ContainingNamespace.IsGlobalNamespace
            ? type.MetadataName
            : $"{type.ContainingNamespace.ToDisplayString()}.{type.MetadataName}";
    }
}
