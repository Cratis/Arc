using System.Collections.Immutable;
using System.Text;
using Cratis.Arc.Queries.ModelBound;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Cratis.Arc.Generators;

/// <summary>
/// Generates the members the validation traversal walks for the model types reachable from model-bound commands and
/// query arguments, registered with typed getters so the traversal does not reflect over them.
/// </summary>
[Generator]
public class ModelGraphWalkerGenerator : IIncrementalGenerator
{
    const string CommandAttribute = "Cratis.Arc.Commands.ModelBound.CommandAttribute";
    const string ReadModelAttribute = "Cratis.Arc.Queries.ModelBound.ReadModelAttribute";
    const string Walkers = "Cratis.Arc.Validation.ModelGraphWalkers";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // The attribute steps only find the roots; the model graph is walked once per compilation from all of them,
        // so model types shared between commands and queries are only visited once.
        var commands = context.SyntaxProvider.ForAttributeWithMetadataName(
            CommandAttribute,
            static (node, _) => node is TypeDeclarationSyntax,
            static (syntax, _) => syntax.TargetSymbol is INamedTypeSymbol command ? MetadataNameOf(command) : string.Empty)
            .Collect();

        var readModels = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is TypeDeclarationSyntax,
            static (syntax, _) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node) is INamedTypeSymbol readModel &&
                (readModel.GetAttributes().Any(_ => _.AttributeClass?.ToDisplayString() == ReadModelAttribute) || ModelBoundQueryMethodSymbols.RequiresQueryAttribute(readModel))
                    ? MetadataNameOf(readModel) : string.Empty)
            .Collect();

        var validators = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
            static (syntax, _) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node) is INamedTypeSymbol validator && CommandReadModelKeyGeneration.ValidatedType(validator) is not null
                ? MetadataNameOf(validator) : string.Empty)
            .Collect();

        var walkers = commands.Combine(readModels).Combine(context.CompilationProvider)
            .Select(static (input, cancellationToken) => WalkersFor(input.Left.Left, input.Left.Right, input.Right, cancellationToken));

        context.RegisterSourceOutput(
            commands.Combine(readModels).Combine(context.CompilationProvider),
            static (output, input) => ProtectedReadModelKeyGeneration.Emit(output, input.Left.Left, input.Left.Right, input.Right));

        context.RegisterSourceOutput(
            commands.Combine(validators).Combine(readModels).Combine(context.CompilationProvider),
            static (output, input) => CommandReadModelKeyGeneration.Emit(output, input.Left.Left.Left, input.Left.Left.Right, input.Left.Right, input.Right));

        context.RegisterSourceOutput(walkers, static (output, walkers) =>
        {
            if (walkers.Count == 0)
            {
                return;
            }

            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Cratis.Arc.Validation.Generated;\ninternal static class ModelGraphWalkerRegistration\n{\n    [global::System.Runtime.CompilerServices.ModuleInitializer]\n    internal static void Initialize()\n    {\n");
            foreach (var walker in walkers)
            {
                source.AppendLine(walker.Registration);
            }

            source.AppendLine("    }\n}");
            output.AddSource("ModelGraphWalkers.g.cs", source.ToString());
        });
    }

    /// <summary>
    /// Finds validation walkers for a compilation's command and query roots.
    /// </summary>
    /// <param name="commands">Command metadata names.</param>
    /// <param name="readModels">Read model metadata names.</param>
    /// <param name="compilation">The consuming compilation.</param>
    /// <param name="cancellationToken">The cancellation token.</param>
    /// <returns>The validation registrations.</returns>
    internal static EquatableArray<ModelGraphWalker> WalkersFor(ImmutableArray<string> commands, ImmutableArray<string> readModels, Compilation compilation, CancellationToken cancellationToken)
    {
        if ((commands.IsEmpty && readModels.IsEmpty) || compilation.GetTypeByMetadataName(Walkers) is null)
        {
            return new([]);
        }

        var roots = TypesNamed(commands, compilation).Cast<ITypeSymbol>()
            .Concat(QueryArgumentTypes(TypesNamed(readModels, compilation), compilation));
        var types = roots.ToArray();
        return new(ModelGraphWalkerTypes.For(types, compilation, cancellationToken)
            .Concat(DataAnnotationMemberTypes.For(types, compilation, cancellationToken))
            .OrderBy(walker => walker.Type, StringComparer.Ordinal));
    }

    /// <summary>
    /// Resolves distinct metadata names within the consuming assembly.
    /// </summary>
    /// <param name="names">The metadata names.</param>
    /// <param name="compilation">The consuming compilation.</param>
    /// <returns>The matching types.</returns>
    internal static IEnumerable<INamedTypeSymbol> TypesNamed(ImmutableArray<string> names, Compilation compilation) =>
        names.Where(name => name.Length > 0)
            .Distinct(StringComparer.Ordinal)
            .Select(compilation.Assembly.GetTypeByMetadataName)
            .OfType<INamedTypeSymbol>();

    /// <summary>
    /// Gets the name a type is found by in its assembly, so a root can be carried between generator steps as a value.
    /// </summary>
    /// <param name="type">The type.</param>
    /// <returns>The metadata name, including namespace and containing types.</returns>
    internal static string MetadataNameOf(INamedTypeSymbol type)
    {
        if (type.ContainingType is { } containing)
        {
            return $"{MetadataNameOf(containing)}+{type.MetadataName}";
        }

        var name = type.MetadataName;
        for (var @namespace = type.ContainingNamespace; @namespace is { IsGlobalNamespace: false }; @namespace = @namespace.ContainingNamespace)
        {
            name = $"{@namespace.MetadataName}.{name}";
        }

        return name;
    }

    /// <summary>
    /// Gets the types read models' queries are validated through: the parameters of their query methods, and the
    /// types that can model a query's argument set by the convention the query pipeline resolves them with.
    /// </summary>
    /// <remarks>
    /// Which parameters are dependencies rather than arguments is only known from the service registrations at
    /// runtime, so every parameter is a root; a dependency only adds walkers that are never used.
    /// </remarks>
    /// <param name="readModels">The read model types.</param>
    /// <param name="compilation">The compilation the generated code is emitted into.</param>
    /// <returns>The types to start from.</returns>
    internal static List<ITypeSymbol> QueryArgumentTypes(IEnumerable<INamedTypeSymbol> readModels, Compilation compilation)
    {
        var roots = new List<ITypeSymbol>();

        // Mirrors QueryArgumentsModelConvention.CandidateNamesFor, which the generator cannot compile in.
        var candidates = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var readModel in readModels)
        {
            var queries = ModelBoundQueryMethodSymbols.GetMethods(
                readModel,
                method => ModelBoundQueryMethodSymbols.IsCandidate(method) && QueryMetadataGenerator.IsValidQueryMethod(method, readModel));
            foreach (var query in queries)
            {
                roots.AddRange(query.Parameters.Select(parameter => parameter.Type));
                candidates.Add($"{readModel.Name}{query.Name}Parameters");
                candidates.Add($"{query.Name}Parameters");
            }
        }

        // One scan of the declarations for all read models.
        if (candidates.Count > 0)
        {
            roots.AddRange(compilation.GetSymbolsWithName(candidates.Contains, SymbolFilter.Type).OfType<ITypeSymbol>());
        }

        return roots;
    }
}
