using System.Reflection;
using Cratis.Arc.Screenplay.Embedded.Generation;
using Xunit;

namespace Company.XunitApplication;

/// <summary>
/// Verifies embedded compiler inputs inside the fixture's own executable process.
/// </summary>
public class ExecutableProof
{
    static Assembly Application => typeof(ExecutableProof).Assembly;

    /// <summary>
    /// Verifies that xUnit supplied the executable entrypoint.
    /// </summary>
    [Fact]
    public void ShouldHaveTheRealXunitGeneratedEntrypoint() => Assert.Contains("XunitAutoGeneratedEntryPoint", Application.EntryPoint!.DeclaringType!.FullName);

    /// <summary>
    /// Verifies that generation embedded the application document.
    /// </summary>
    [Fact]
    public void ShouldEmbedTheApplicationDocument() => Assert.Contains(ReadCatalog().Documents, document => document.Id == "Company.XunitApplication");

    /// <summary>
    /// Verifies that every catalog document has a manifest resource.
    /// </summary>
    [Fact]
    public void ShouldEmbedEveryCatalogDocument() => Assert.All(ReadCatalog().Documents, document => Assert.Contains(document.ResourceName, Application.GetManifestResourceNames()));

    /// <summary>
    /// Verifies that the existing resource pipeline still completes.
    /// </summary>
    [Fact]
    public void ShouldPreserveTheResourcePipeline() => Assert.Contains("Company.XunitApplication.Messages.resources", Application.GetManifestResourceNames());

    static EmbeddedDocumentCatalog ReadCatalog()
    {
        using var stream = Application.GetManifestResourceStream(EmbeddedResourceNames.Catalog)!;
        using var reader = new StreamReader(stream);
        return EmbeddedDocumentCatalog.Deserialize(reader.ReadToEnd());
    }
}
