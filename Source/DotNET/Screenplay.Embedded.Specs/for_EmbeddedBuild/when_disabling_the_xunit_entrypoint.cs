namespace Cratis.Arc.Screenplay.Embedded.for_EmbeddedBuild;

public class when_disabling_the_xunit_entrypoint : given.an_xunit_fixture_process
{
    async Task Because() => await RunProcess(
        "build",
        "Source/DotNET/Screenplay.Embedded.Specs/Fixtures/XunitConsumer/XunitConsumer.csproj",
        "-c",
        "Release",
        "-f",
        $"net{Environment.Version.Major}.0",
        "--no-restore",
        "-m:3",
        "-p:BuildProjectReferences=false",
        "-p:XunitAutoGeneratedEntryPoint=false");

    [Fact] void should_reject_the_executable_without_a_main() => Assert.True(_exitCode != 0, _output);
    [Fact] void should_preserve_the_embedded_source_compilation_rejection() => _output.ShouldContain("error SP0024");
    [Fact] void should_report_the_missing_compiler_entrypoint() => _output.ShouldContain("Program does not contain a static 'Main' method suitable for an entry point");
    [Fact] void should_not_introduce_a_target_cycle() => _output.ShouldNotContain("MSB4006");
    [Fact] void should_not_depend_on_a_missing_target() => _output.ShouldNotContain("MSB4057");
}
