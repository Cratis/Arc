using System.Text;
using System.Text.RegularExpressions;

namespace Cratis.Arc.ProxyGenerator;

/// <summary>Compares complete expected artifacts without modifying the output tree.</summary>
/// <param name="outputPath">The output root.</param>
internal sealed partial class CheckingGeneratedOutput(string outputPath) : IGeneratedOutput
{
    readonly string _root = Path.GetFullPath(outputPath);
    readonly Dictionary<string, string> _expected = new(StringComparer.Ordinal);

    /// <summary>Gets the comparison findings.</summary>
    public DriftReport Report { get; } = new();

    /// <inheritdoc/>
    public bool ComparesBytes => true;

    /// <inheritdoc/>
    public void EnsureDirectory(string path) => RelativePath(path);

    /// <inheritdoc/>
    public async Task WriteFile(string path, string content)
    {
        var relative = RelativePath(path);
        path = Path.GetFullPath(path);
        if (_expected.TryGetValue(path, out var previous) && previous != content)
        {
            throw new InvalidOperationException($"Conflicting generated contents for '{relative}'.");
        }
        _expected[path] = content;
        if (!File.Exists(path))
        {
            Report.Add("missing", relative);
            return;
        }

        var actual = await File.ReadAllBytesAsync(path);
        var expected = PreserveTimestamp(path, content);
        if (!actual.AsSpan().SequenceEqual(Encoding.UTF8.GetBytes(expected))) Report.Add("changed", relative);
    }

    /// <inheritdoc/>
    public void DeleteFile(string path) => Report.Add("obsolete", RelativePath(path));

    /// <inheritdoc/>
    public void DeleteDirectoryIfEmpty(string path) => RelativePath(path);

    static string PreserveTimestamp(string path, string expected)
    {
        if (!GeneratedFileMetadata.IsGeneratedFile(path, out _)) return expected;
        var actualLine = File.ReadLines(path).FirstOrDefault(line => GeneratedFileMetadata.TryParse(line, out _));
        var timestamp = MetadataTime().Match(actualLine ?? string.Empty);
        return timestamp.Success ? MetadataTime().Replace(expected, match => match.Groups["prefix"].Value + timestamp.Groups["time"].Value + match.Groups["suffix"].Value, 1) : expected;
    }

    [GeneratedRegex(@"^(?<prefix>// @generated by Cratis\. Source: .*?\. Time: )(?<time>.*?)(?<suffix>\. Hash: [^\r\n]*|\r?$)", RegexOptions.Multiline | RegexOptions.ExplicitCapture, 1000)]
    private static partial Regex MetadataTime();

    string RelativePath(string path)
    {
        var relative = Path.GetRelativePath(_root, Path.GetFullPath(path));
        if (Path.IsPathRooted(relative) || relative == ".." || relative.StartsWith($"..{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
        {
            throw new InvalidOperationException($"Generated path '{path}' escapes the output directory.");
        }
        return relative.Replace('\\', '/');
    }
}
