using System.Text.RegularExpressions;

namespace Cratis.Arc.ProxyGenerator;

/// <summary>
/// Provides functionality to intelligently manage index.ts files.
/// </summary>
public static partial class IndexFileManager
{
    static readonly string[] _typeScriptExtensions = [".ts", ".tsx"];

    /// <summary>
    /// Updates or creates an index.ts file for a directory, preserving manual edits.
    /// </summary>
    /// <param name="directory">The directory to create/update the index.ts file in.</param>
    /// <param name="generatedFiles">Dictionary of generated file paths (full paths) to their metadata.</param>
    /// <param name="orphanedFiles">Collection of orphaned file paths that were deleted.</param>
    /// <param name="message">Logger to use for outputting messages.</param>
    /// <param name="outputPath">The base output path for relative path calculation.</param>
    /// <returns>True if the index file was written, false if skipped.</returns>
    public static bool UpdateIndexFile(string directory, IDictionary<string, GeneratedFileMetadata> generatedFiles, IEnumerable<string> orphanedFiles, Action<string> message, string outputPath) =>
        UpdateIndexFileWithFileHeader(string.Empty, directory, generatedFiles, orphanedFiles, message, outputPath);

    /// <summary>
    /// Updates index.ts files in generated directories and existing index directories with potentially stale exports.
    /// </summary>
    /// <param name="directories">Collection of directories with generated content.</param>
    /// <param name="generatedFiles">Collection of all generated file paths.</param>
    /// <param name="orphanedFiles">Collection of orphaned file paths that were deleted.</param>
    /// <param name="message">Logger to use for outputting messages.</param>
    /// <param name="outputPath">The base output path.</param>
    /// <returns>A tuple containing (WrittenCount, SkippedCount).</returns>
    public static (int WrittenCount, int SkippedCount) UpdateAllIndexFiles(IEnumerable<string> directories, IDictionary<string, GeneratedFileMetadata> generatedFiles, IEnumerable<string> orphanedFiles, Action<string> message, string outputPath) =>
        UpdateAllIndexFilesWithFileHeader(string.Empty, directories, generatedFiles, orphanedFiles, message, outputPath);

    /// <inheritdoc cref="UpdateIndexFile"/>
    internal static bool UpdateIndexFileWithFileHeader(string fileHeaderTemplate, string directory, IDictionary<string, GeneratedFileMetadata> generatedFiles, IEnumerable<string> orphanedFiles, Action<string> message, string outputPath) =>
        UpdateDirectoryIndex(new IndexLocation(directory, generatedFiles), GroupByDirectory(generatedFiles, orphanedFiles), new IndexOutput(fileHeaderTemplate, message, outputPath));

    /// <summary>
    /// Updates the index.ts file of one directory from files already grouped by directory.
    /// </summary>
    /// <param name="location">The index.ts directory and the generated files tracked for this run.</param>
    /// <param name="byDirectory">The generated and orphaned files, grouped by directory.</param>
    /// <param name="output">The file header and diagnostic output settings.</param>
    /// <returns>True if the index file was written, false if skipped.</returns>
    static bool UpdateDirectoryIndex(IndexLocation location, Dictionary<string, DirectoryFiles> byDirectory, IndexOutput output)
    {
        var indexPath = location.IndexPath;
        var inDirectory = byDirectory.GetValueOrDefault(location.Directory) ?? DirectoryFiles.None;

        // If there are no generated files in this directory, only delete the
        // existing index.ts if it was itself generated by this tool. Hand-written
        // index files are never touched regardless of their content.
        if (inDirectory.FileNames.Count == 0)
        {
            DeleteEmptyGeneratedIndex(location, output);
            return false;
        }

        var (existingExports, manualLines) = ParseIndexFile(location);

        var hasStaleExports = existingExports.Exists(_ => IsStaleExport(_, location));
        if (!NeedsRewrite(inDirectory, hasStaleExports, location))
        {
            return false;
        }

        var finalExports = BuildFinalExports(existingExports, inDirectory, location);

        // Check if anything changed (compare unsorted since we preserve order)
        if (existingExports.SequenceEqual(finalExports))
        {
            // No changes - don't rewrite
            return false;
        }

        var content = BuildIndexContent(output, location, manualLines, finalExports);

        // If the file exists, compare a normalized version (trim and ignore empty lines)
        if (File.Exists(indexPath) && Normalize(File.ReadAllText(indexPath)) == Normalize(content))
        {
            // Equivalent content (ignoring blank lines/trim) — don't rewrite
            return false;
        }

        File.WriteAllText(indexPath, content);
        output.Message($"    Updated index: {GetRelativePath(output, indexPath)}");
        return true;
    }

    /// <inheritdoc cref="UpdateAllIndexFiles"/>
    internal static (int WrittenCount, int SkippedCount) UpdateAllIndexFilesWithFileHeader(string fileHeaderTemplate, IEnumerable<string> directories, IDictionary<string, GeneratedFileMetadata> generatedFiles, IEnumerable<string> orphanedFiles, Action<string> message, string outputPath)
    {
        // Combine explicitly tracked directories with any directory under outputPath
        // that has an existing index.ts file, to catch stale exports from previous runs.
        var allDirectories = new HashSet<string>(directories, StringComparer.Ordinal);

        if (Directory.Exists(outputPath))
        {
            foreach (var dir in Directory.GetFiles(outputPath, "index.ts", SearchOption.AllDirectories).Select(Path.GetDirectoryName).OfType<string>())
            {
                allDirectories.Add(dir);
            }
        }

        // Grouping once keeps this linear in the number of files, rather than a scan of every file per directory.
        var byDirectory = GroupByDirectory(generatedFiles, orphanedFiles);

        var output = new IndexOutput(fileHeaderTemplate, message, outputPath);
        var writtenCount = allDirectories.Count(_ => UpdateDirectoryIndex(new IndexLocation(_, generatedFiles), byDirectory, output));
        return (writtenCount, allDirectories.Count - writtenCount);
    }

    static void DeleteEmptyGeneratedIndex(IndexLocation location, IndexOutput output)
    {
        if (!IsDeletableIndex(location))
        {
            return;
        }

        File.Delete(location.IndexPath);
        output.Message($"    Deleted empty index: {GetRelativePath(output, location.IndexPath)}");
    }

    static bool IsDeletableIndex(IndexLocation location) =>
        File.Exists(location.IndexPath) &&
        GeneratedFileMetadata.IsGeneratedFile(location.IndexPath, out _) &&
        !HasLiveNonGeneratedExports(location);

    static (List<string> Exports, List<string> ManualLines) ParseIndexFile(IndexLocation location)
    {
        var exports = new List<string>();
        var manualLines = new List<string>();

        if (!File.Exists(location.IndexPath))
        {
            return (exports, manualLines);
        }

        foreach (var line in File.ReadAllLines(location.IndexPath))
        {
            var match = ExportRegex().Match(line);
            if (match.Success)
            {
                exports.Add(match.Groups["path"].Value);
            }
            else if (!string.IsNullOrWhiteSpace(line))
            {
                // Keep non-export lines (comments, imports, etc.)
                manualLines.Add(line);
            }
        }

        return (exports, manualLines);
    }

    /// <summary>
    /// Checks whether an existing export points at a file that is neither on disk nor tracked as generated.
    /// </summary>
    /// <param name="export">The export path as written in the index.</param>
    /// <param name="location">The index.ts directory and the generated files tracked for this run.</param>
    /// <returns><see langword="true"/> if the export is stale; otherwise <see langword="false"/>.</returns>
    static bool IsStaleExport(string export, IndexLocation location)
    {
        // A non-relative (bare/package) specifier, e.g. '@cratis/components', is never something the
        // generator wrote and never something it can verify on disk — treat it as manual, never stale.
        if (!export.StartsWith('.'))
        {
            return false;
        }

        // A relative export whose target file no longer exists on disk and is not tracked as a current
        // generated file (it may not have been written this run because the content was unchanged) is stale.
        var fileName = export.TrimStart('.', '/');
        return !ExportTargetExistsOnDisk(location, fileName) && !location.GeneratedFiles.ContainsKey(Path.GetFullPath(Path.Combine(location.Directory, $"{fileName}.ts")));
    }

    /// <summary>
    /// Starts with the existing exports, removing orphans and exports for files that no longer exist on disk
    /// (e.g. after source file grouping changes), then inserts each new export individually at its best-effort
    /// alphabetical position.
    /// </summary>
    /// <param name="existingExports">The exports currently in the index.</param>
    /// <param name="inDirectory">The generated and orphaned files in the index's directory.</param>
    /// <param name="location">The index.ts directory and the generated files tracked for this run.</param>
    /// <returns>The exports the index should contain.</returns>
    static List<string> BuildFinalExports(List<string> existingExports, DirectoryFiles inDirectory, IndexLocation location)
    {
        var finalExports = existingExports
            .Where(_ => !inDirectory.OrphanedFileNames.Contains(_.TrimStart('.', '/')) && !IsStaleExport(_, location))
            .ToList();

        // Collect new exports to add (only those not already in the index)
        var existingFileNames = existingExports.Select(_ => _.TrimStart('.', '/')).ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (var newFileName in inDirectory.FileNames.Where(_ => !existingFileNames.Contains(_)).ToList())
        {
            finalExports.Insert(FindInsertIndex(finalExports, newFileName), $"./{newFileName}");
        }

        return finalExports;
    }

    /// <summary>
    /// Finds the best position: before the first export that's alphabetically greater, otherwise the end.
    /// </summary>
    /// <param name="exports">The exports to insert into.</param>
    /// <param name="newFileName">The file name of the new export.</param>
    /// <returns>The index to insert the new export at.</returns>
    static int FindInsertIndex(List<string> exports, string newFileName)
    {
        var index = exports.FindIndex(_ => string.Compare(newFileName, _.TrimStart('.', '/'), StringComparison.OrdinalIgnoreCase) < 0);
        return index < 0 ? exports.Count : index;
    }

    static string BuildIndexContent(IndexOutput output, IndexLocation location, List<string> manualLines, List<string> exports)
    {
        // Manual lines first (comments, imports, etc.), then the export statements
        var contentLines = manualLines.Concat(exports.Select(_ => $"export * from '{_}';"));

        var header = File.Exists(location.IndexPath) ? string.Empty : FileHeader.Format(output.FileHeaderTemplate, location.IndexPath);
        var content = header + string.Join(Environment.NewLine, contentLines);
        return string.IsNullOrEmpty(content) ? content : content + Environment.NewLine;
    }

    static string Normalize(string content) => string.Join('\n', content.Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries).Select(_ => _.Trim()));

    /// <summary>
    /// Checks whether an existing index.ts has at least one export whose target file
    /// exists on disk but is not a proxy-generated file (e.g. hand-written .tsx components).
    /// </summary>
    /// <param name="location">The index.ts file to inspect.</param>
    /// <returns><see langword="true"/> if a live non-generated export exists; otherwise <see langword="false"/>.</returns>
    static bool HasLiveNonGeneratedExports(IndexLocation location) =>
        File.ReadAllLines(location.IndexPath)
            .Select(_ => ExportRegex().Match(_))
            .Any(_ => _.Success && IsLiveNonGeneratedExport(_.Groups["path"].Value, location));

    static bool IsLiveNonGeneratedExport(string exportPath, IndexLocation location)
    {
        // A non-relative (bare/package) specifier is always hand-written.
        if (!exportPath.StartsWith('.'))
        {
            return true;
        }

        var fileName = exportPath.TrimStart('.', '/');

        // Check common TypeScript extensions for the export target
        var existingFiles = _typeScriptExtensions
            .Select(_ => Path.Combine(location.Directory, $"{fileName}{_}"))
            .Where(File.Exists)
            .ToList();

        // A directory export with its own barrel is, by construction, hand-written — the generator
        // has never written a folder export — so it counts as a live non-generated export even though
        // there is no single file to check for the @generated marker.
        if (existingFiles.Count == 0)
        {
            return DirectoryBarrelExists(location, fileName);
        }

        // If a file is not proxy-generated, this is a live non-generated export
        return existingFiles.Exists(file => !GeneratedFileMetadata.IsGeneratedFile(file, out _));
    }

    /// <summary>
    /// Checks whether an export target resolves to a generated file or a hand-written directory barrel on disk.
    /// </summary>
    /// <param name="location">The index.ts directory and the generated files tracked for this run.</param>
    /// <param name="fileName">The relative export target, with any leading <c>./</c> and extension stripped.</param>
    /// <returns><see langword="true"/> if the target resolves to a <c>.ts</c>/<c>.tsx</c> file or to a directory with its own barrel.</returns>
    /// <remarks>
    /// An export can also target a directory with its own <c>index.ts</c>/<c>index.tsx</c> barrel, e.g.
    /// <c>export * from './List';</c> where <c>List/</c> is a hand-written folder. The generator has never written
    /// a folder export — the export list it builds is always sourced from generated *files* in this directory — so
    /// a folder export is by construction hand-written and must never be pruned as stale. Requiring the child
    /// barrel to exist (rather than merely the directory) mirrors how TypeScript resolves a bare directory
    /// specifier, and keeps pruning honest for a folder that exports nothing: an absent <c>List.ts</c> is not, on
    /// its own, proof that the target is gone — it may simply be a folder export instead.
    /// </remarks>
    static bool ExportTargetExistsOnDisk(IndexLocation location, string fileName)
    {
        foreach (var ext in (string[])[".ts", ".tsx"])
        {
            if (File.Exists(Path.Combine(location.Directory, $"{fileName}{ext}")))
            {
                return true;
            }
        }

        return DirectoryBarrelExists(location, fileName);
    }

    /// <summary>
    /// Checks whether a relative export target resolves to a directory containing its own barrel file.
    /// </summary>
    /// <param name="location">The index.ts directory and the generated files tracked for this run.</param>
    /// <param name="fileName">The relative export target, with any leading <c>./</c> stripped.</param>
    /// <returns><see langword="true"/> if <paramref name="fileName"/> is a subdirectory of the directory in <paramref name="location"/> with an <c>index.ts</c> or <c>index.tsx</c> file.</returns>
    static bool DirectoryBarrelExists(IndexLocation location, string fileName)
    {
        var childDirectory = Path.Combine(location.Directory, fileName);
        return Directory.Exists(childDirectory) &&
            (File.Exists(Path.Combine(childDirectory, "index.ts")) || File.Exists(Path.Combine(childDirectory, "index.tsx")));
    }

    /// <summary>
    /// Decides whether an index.ts must be rewritten.
    /// </summary>
    /// <param name="inDirectory">The generated and orphaned files in the index's directory.</param>
    /// <param name="hasStaleExports">Whether the existing index exports files that no longer exist.</param>
    /// <param name="location">The index.ts file to inspect.</param>
    /// <returns><see langword="true"/> when files were written or orphaned in the directory, the index has stale exports, or the index is missing (for example a deleted index.ts).</returns>
    static bool NeedsRewrite(DirectoryFiles inDirectory, bool hasStaleExports, IndexLocation location) =>
        inDirectory.AnyWritten || inDirectory.OrphanedFileNames.Count > 0 || hasStaleExports || !File.Exists(location.IndexPath);

    [GeneratedRegex(@"^\s*export\s+\*\s+from\s+['""](?<path>.+)['""]\s*;?\s*$", RegexOptions.ExplicitCapture, 1000)]
    private static partial Regex ExportRegex();

    static string GetRelativePath(IndexOutput output, string fullPath)
    {
        if (fullPath.StartsWith(output.OutputPath, StringComparison.OrdinalIgnoreCase))
        {
            var relative = fullPath[output.OutputPath.Length..].TrimStart(Path.DirectorySeparatorChar);
            return relative.Replace(Path.DirectorySeparatorChar, '/');
        }

        return fullPath;
    }

    static Dictionary<string, DirectoryFiles> GroupByDirectory(IDictionary<string, GeneratedFileMetadata> generatedFiles, IEnumerable<string> orphanedFiles)
    {
        var byDirectory = new Dictionary<string, DirectoryFiles>(StringComparer.Ordinal);

        foreach (var (path, metadata) in generatedFiles)
        {
            if (Path.GetDirectoryName(path) is not { } directory)
            {
                continue;
            }

            var files = DirectoryFilesOf(byDirectory, directory);
            files.FileNames.Add(Path.GetFileNameWithoutExtension(path));
            files.AnyWritten |= metadata.WasWritten;
        }

        foreach (var path in orphanedFiles.Where(_ => Path.GetDirectoryName(_) is not null))
        {
            DirectoryFilesOf(byDirectory, Path.GetDirectoryName(path)!).OrphanedFileNames.Add(Path.GetFileNameWithoutExtension(path));
        }

        return byDirectory;
    }

    static DirectoryFiles DirectoryFilesOf(Dictionary<string, DirectoryFiles> byDirectory, string directory)
    {
        if (!byDirectory.TryGetValue(directory, out var files))
        {
            files = new DirectoryFiles();
            byDirectory[directory] = files;
        }

        return files;
    }

    /// <summary>
    /// Represents the generated and orphaned files of one directory.
    /// </summary>
    internal sealed class DirectoryFiles
    {
        /// <summary>
        /// Gets the files of a directory that has none.
        /// </summary>
        public static readonly DirectoryFiles None = new();

        /// <summary>
        /// Gets the names, without extension, of the generated files.
        /// </summary>
        public HashSet<string> FileNames { get; } = new(StringComparer.OrdinalIgnoreCase);

        /// <summary>
        /// Gets the names, without extension, of the orphaned files.
        /// </summary>
        public HashSet<string> OrphanedFileNames { get; } = new(StringComparer.OrdinalIgnoreCase);

        /// <summary>
        /// Gets or sets a value indicating whether any generated file was written.
        /// </summary>
        public bool AnyWritten { get; set; }
    }

    /// <summary>
    /// Represents the file header and diagnostic output settings shared by index updates.
    /// </summary>
    /// <param name="FileHeaderTemplate">The file header template for a newly created index file.</param>
    /// <param name="Message">Logger to use for outputting messages.</param>
    /// <param name="OutputPath">The base output path for relative path calculation.</param>
    sealed record IndexOutput(string FileHeaderTemplate, Action<string> Message, string OutputPath);

    /// <summary>
    /// Represents the directory of an index.ts file together with the generated files tracked for this run.
    /// </summary>
    /// <param name="Directory">The directory containing the index.ts file.</param>
    /// <param name="GeneratedFiles">Dictionary of generated file paths (full paths) to their metadata.</param>
    sealed record IndexLocation(string Directory, IDictionary<string, GeneratedFileMetadata> GeneratedFiles)
    {
        /// <summary>
        /// Gets the path of the index.ts file.
        /// </summary>
        public string IndexPath => Path.Combine(Directory, "index.ts");
    }
}
