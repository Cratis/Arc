import { ESLint } from 'eslint';
import parser from '@typescript-eslint/parser';
import config from '../../../../../eslint.config.mjs';
import ts from 'typescript-for-eslint';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';

let input = '';
for await (const chunk of process.stdin) input += chunk;
const fixtures = JSON.parse(input);
if (fixtures.length !== 44) throw new Error(`Expected 44 generated fixtures, got ${fixtures.length}`);
if (!fixtures.every(content => /^\/\/ Copyright \(c\) Cratis\. All rights reserved\.\r?\n\/\/ Licensed under the MIT license\. See LICENSE file in the project root for full license information\.\r?\n\r?\n\/\/ @generated by Cratis/.test(content))) {
    throw new Error('Direct lint fixtures must retain their actual generated metadata envelope');
}

// This is the consuming-app contract, not Arc's authored-library policy.
// Public empty interfaces support declaration merging and non-nullish assignability.
const appPolicy = {
    files: ['**/*.ts'],
    linterOptions: { reportUnusedDisableDirectives: 'error' },
    rules: { '@typescript-eslint/no-empty-object-type': 'off' }
};
const strictPolicy = {
    files: ['**/*.ts'],
    rules: {
        'sort-imports': ['error', { ignoreDeclarationSort: true }],
        '@typescript-eslint/ban-ts-comment': 'error'
    }
};
const profiles = {
    app: [...config, appPolicy],
    'app-extra-checks': [...config, appPolicy, strictPolicy],
    minimal: [{ files: ['**/*.ts'], languageOptions: { parser }, linterOptions: { reportUnusedDisableDirectives: 'error' } }]
};
// Always exercise actual ESLint 9 in CI, without changing repository dependencies.
// npm exec installs the pinned checker in its external tool cache when root uses ESLint 10.
const require = createRequire(import.meta.url);
const eslint9Path = ESLint.version.startsWith('9.') ? require.resolve('eslint') : execFileSync('npm', [
    'exec', '--yes', '--package=eslint@9.39.4', '--', 'node', '-e',
    `const fs = require('node:fs'); const path = require('node:path');
    const cli = process.env.PATH.split(path.delimiter).map(dir => path.join(dir, 'eslint')).find(file => fs.existsSync(file));
    if (!cli) throw new Error('npm exec did not expose ESLint');
    console.log(path.resolve(path.dirname(fs.realpathSync(cli)), '../lib/api.js'));`
], { encoding: 'utf8', timeout: 120000 }).trim();
const ESLint9 = require(eslint9Path).ESLint;
if (!ESLint9.version.startsWith('9.')) throw new Error(`Expected actual ESLint 9, got ${ESLint9.version}`);
const runners = [{ name: 'root', Core: ESLint, profiles }, { name: 'actual9', Core: ESLint9, profiles: { ...profiles } }];
// Optional read-only verification against an installed consuming app.
let consumerESLint;
if (process.env.ARC_CONSUMER_ESLINT_CONFIG) {
    const configPath = path.resolve(process.env.ARC_CONSUMER_ESLINT_CONFIG);
    const consumerConfig = (await import(pathToFileURL(configPath))).default;
    const installedCore = createRequire(configPath)('eslint').ESLint;
    consumerESLint = installedCore.version.startsWith('9.') ? installedCore : ESLint9;
    if (!consumerESLint.version.startsWith('9.')) throw new Error(`Expected loaded Direct checker ESLint 9, got ${consumerESLint.version}`);
    console.log(`Read-only Direct config: ${configPath}; installed checker ${installedCore.version}; loaded checker ${consumerESLint.version}`);
    runners.push({ name: 'installed-consumer', Core: consumerESLint, profiles: { app: [...consumerConfig, {
        files: ['**/*.ts'], linterOptions: { reportUnusedDisableDirectives: 'error' }
    }] } });
}
let failures = 0;
const checks = runners.flatMap(({ name, Core, profiles: runnerProfiles }) =>
    Object.entries(runnerProfiles).map(([mode, overrideConfig]) => ({ name, Core, mode, overrideConfig })));
for (const { name, Core, mode, overrideConfig } of checks) {
    const eslint = new Core({ overrideConfigFile: true, overrideConfig });
    for (const [index, content] of fixtures.entries()) {
        const filePath = `Source/GeneratedFixture${index}.ts`;
        const effective = await eslint.calculateConfigForFile(filePath);
        if (!effective || effective.processor || await eslint.isPathIgnored(filePath)) {
            throw new Error(`${name}/${mode}: fixture ${index} is not configured for direct linting`);
        }
        for (const result of await eslint.lintText(content, { filePath })) {
            failures += result.errorCount + result.warningCount;
            if (result.messages.length) console.log(mode, index, result.messages);
        }
    }
    // Prove the profile has not waived unused directives, including without rule plugins.
    const [planted] = await eslint.lintText(`${fixtures[0]}\n/* eslint-disable no-debugger */\n`, { filePath: 'Source/GeneratedFixture0.ts' });
    if (!planted.messages.some(message => message.message.includes('Unused eslint-disable directive') && message.severity === 2)) {
        throw new Error(`${mode} failed to reject an unused directive`);
    }
    if (mode === 'app-extra-checks') {
        const defects = [
            ['@tony.ganchev/header', fixtures[0].replace('// Copyright (c) Cratis. All rights reserved.', '// Missing license')],
            ['sort-imports', fixtures[0].replace('ClearCommandValues, SetCommandValues, useCommand', 'useCommand, SetCommandValues, ClearCommandValues')],
            ['@typescript-eslint/ban-ts-comment', `${fixtures[0]}\n// @ts-ignore\nexport const ignored = 1;`]
        ];
        for (const [ruleId, content] of defects) {
            const [result] = await eslint.lintText(content, { filePath: 'Source/Planted.ts' });
            if (!result.messages.some(message => message.ruleId === ruleId && message.severity === 2)) {
                throw new Error(`${mode} failed to detect planted ${ruleId}`);
            }
        }
    }
    console.log(`${name}/${mode}: actual ESLint ${Core.version}; directly linted ${fixtures.length} marked generated fixtures; marked unused-directive rejection checked`);
}
console.log(`Generated fixture lint: ${failures} diagnostics across ${checks.length} direct checker/config profiles`);

// Compile the real generated response hooks against the built Arc + Arc.React packages.
// No substitute hook signatures or TypeScript suppressions are involved.
const filename = path.resolve('.ai-work/response-hook-contract.ts');
const options = {
    strict: true, noEmit: true, skipLibCheck: true,
    target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler
};
const host = ts.createCompilerHost(options);
const readFile = host.readFile.bind(host);
const fileExists = host.fileExists.bind(host);
host.readFile = file => file === filename ? fixtures.at(-1) : readFile(file);
host.fileExists = file => file === filename || fileExists(file);
const program = ts.createProgram([filename], options, host);
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) console.log(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCurrentDirectory: () => process.cwd(), getCanonicalFileName: file => file, getNewLine: () => '\n'
}));
failures += diagnostics.length;
// The old two-generic number hook must fail, proving the compiler checks the real constraint.
host.readFile = file => file === filename
    ? fixtures.at(-1).replace('useCommand<NumberResponse, INumberResponse, number>', 'useCommand<NumberResponse, INumberResponse>')
    : readFile(file);
const oldHookDiagnostics = ts.getPreEmitDiagnostics(ts.createProgram([filename], options, host));
if (!oldHookDiagnostics.some(diagnostic => diagnostic.code === 2344)) {
    throw new Error('The compiler did not reject the old two-generic number response hook');
}
console.log(`Compiled 5 generated command response hooks (number/custom/enum/array/void) against actual Arc.React: ${diagnostics.length} diagnostics`);
process.exitCode = failures ? 1 : 0;
