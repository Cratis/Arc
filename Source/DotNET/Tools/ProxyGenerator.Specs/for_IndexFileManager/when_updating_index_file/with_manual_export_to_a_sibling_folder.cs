namespace Cratis.Arc.ProxyGenerator.for_IndexFileManager.when_updating_index_file;

public class with_manual_export_to_a_sibling_folder : Specification
{
    string _tempDir;
    List<string> _messages;
    string _indexPath;
    bool _firstResult;
    bool _secondResult;

    void Establish()
    {
        _tempDir = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString());
        Directory.CreateDirectory(_tempDir);

        // Generated .ts file (content unchanged, so WasWritten = false)
        File.WriteAllText(Path.Combine(_tempDir, "RegisterFacility.ts"), "// @generated by Cratis. Source: RegisterFacility. Time: 2025-01-01T00:00:00.0000000Z. Hash: ABC\nexport class RegisterFacility {}");

        // Hand-written sibling folder with its own barrel — the generator has never written a folder export.
        var listDir = Path.Combine(_tempDir, "List");
        Directory.CreateDirectory(listDir);
        File.WriteAllText(Path.Combine(listDir, "index.ts"), "export * from './FacilityList';\n");

        // Existing index.ts exporting both the generated file and the sibling folder.
        _indexPath = Path.Combine(_tempDir, "index.ts");
        File.WriteAllText(_indexPath, "export * from './RegisterFacility';\nexport * from './List';\n");

        _messages = [];
    }

    void Because()
    {
        var dict = new Dictionary<string, GeneratedFileMetadata>
        {
            [Path.Combine(_tempDir, "RegisterFacility.ts")] = new GeneratedFileMetadata("RegisterFacility", DateTime.UtcNow, GeneratedFileMetadata.ComputeHash(""), false),
        };

        // Run twice to prove the fix is idempotent — neither run should touch the file.
        _firstResult = IndexFileManager.UpdateIndexFile(_tempDir, dict, [], _messages.Add, _tempDir);
        _secondResult = IndexFileManager.UpdateIndexFile(_tempDir, dict, [], _messages.Add, _tempDir);
    }

    [Fact] void should_not_rewrite_index_on_first_run() => _firstResult.ShouldBeFalse();
    [Fact] void should_not_rewrite_index_on_second_run() => _secondResult.ShouldBeFalse();
    [Fact] void should_preserve_folder_export() => File.ReadAllText(_indexPath).ShouldContain("export * from './List';");
    [Fact] void should_preserve_generated_export() => File.ReadAllText(_indexPath).ShouldContain("export * from './RegisterFacility';");

    void Cleanup()
    {
        if (Directory.Exists(_tempDir))
        {
            Directory.Delete(_tempDir, true);
        }
    }
}
